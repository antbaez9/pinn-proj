# Organize data
pinn_data = [eigenvalues_adv_pinn, eigenvalues_wave_pinn, eigenvalues_kdv_pinn]
proj_data = [eigenvalues_adv_proj, eigenvalues_wave_proj, eigenvalues_kdv_proj]
titles = ['Advection Equation', 'Wave Equation', 'Korteweg-De Vries Equation']

# Create 1x3 subplot grid
fig, axes = plt.subplots(1, 3, figsize=(18, 4))

# Plot each spectrum
for i in range(3):
    ax = axes[i]
    
    # FIX 1: Set evaluation range based on actual data, not arbitrary wide range
    all_eigenvalues = np.concatenate([pinn_data[i], proj_data[i]])
    data_min = np.min(all_eigenvalues)
    data_max = np.max(all_eigenvalues)
    
    # Add some padding (10-20%) around the actual data range
    padding = 0.2 * (data_max - data_min)
    x_min = data_min - padding
    x_max = data_max + padding
    
    # Create evaluation grid over the actual data range
    n_points = 10000  # Still fine resolution, but over appropriate range
    x_range = np.linspace(x_min, x_max, n_points)
    
    # FIX 2: Use smaller bandwidth for less over-smoothing
    # Create KDE for PINN eigenvalues
    if len(pinn_data[i]) > 1:
        pinn_kde = gaussian_kde(pinn_data[i])
        # Use smaller bandwidth for more detailed curves
        pinn_kde.set_bandwidth(pinn_kde.factor * 0.01)  # Even smaller bandwidth
        pinn_density = pinn_kde(x_range)
        
        # Normalize or ensure minimum for log scale
        pinn_density = np.maximum(pinn_density, 1e-12)
        ax.plot(x_range, pinn_density, 'b-', linewidth=3, label='PINN')
    
    # Create KDE for PINN-Proj eigenvalues
    if len(proj_data[i]) > 1:
        proj_kde = gaussian_kde(proj_data[i])
        proj_kde.set_bandwidth(proj_kde.factor * 0.01)  # Match bandwidth
        proj_density = proj_kde(x_range)
        
        proj_density = np.maximum(proj_density, 1e-12)
        ax.plot(x_range, proj_density, 'r-', linewidth=3, label='PINN-Proj')
    
    # FIX 3: Set appropriate axis limits based on data
    ax.set_xscale('symlog', linthresh=0.01, linscale=0.5)
    ax.set_yscale('log')
    
    # Set limits based on actual data range
    ax.set_xlim(x_min, x_max)
    
    # Set y-limits based on actual density values, not arbitrary
    all_densities = []
    if len(pinn_data[i]) > 1:
        all_densities.extend(pinn_density)
    if len(proj_data[i]) > 1:
        all_densities.extend(proj_density)
    
    if all_densities:
        y_min = max(np.min(all_densities) * 0.1, 1e-12)
        y_max = np.max(all_densities) * 10
        ax.set_ylim(y_min, y_max)
    
    # Labels and formatting
    ax.set_xlabel('Eigenvalue')
    if i == 0:
        ax.set_ylabel('Density')
    ax.set_title(titles[i])
    
    # Add grid for better readability
    ax.grid(True, alpha=0.3)

# Create unified legend
